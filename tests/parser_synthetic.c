#include "parser.h"

#include <assert.h>
#include <netinet/ip_icmp.h>
#include <netinet/tcp.h>
#include <stdio.h>
#include <string.h>

static void test_truncated_ethernet(void)
{
    static const uint8_t truncated_packet[10] = {0};
    PacketInfo info;

    assert(!parse_packet(truncated_packet, sizeof(truncated_packet), sizeof(truncated_packet), &info));
    assert(info.truncated);
    assert(!info.has_ethernet);
}

static void test_arp_request(void)
{
    static const uint8_t packet[] = {
        0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55,
        0x08, 0x06,
        0x00, 0x01, 0x08, 0x00, 0x06, 0x04, 0x00, 0x01,
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55,
        0xc0, 0xa8, 0x01, 0x0a,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0xc0, 0xa8, 0x01, 0x01
    };
    PacketInfo info;

    assert(parse_packet(packet, sizeof(packet), sizeof(packet), &info));
    assert(info.has_arp);
    assert(info.arp_opcode == 1U);
    assert(memcmp(info.arp_sender_mac, &packet[22], 6U) == 0);
}

static void test_ipv4_tcp_with_options(void)
{
    static const uint8_t packet[] = {
        0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff,
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55,
        0x08, 0x00,
        0x46, 0x00, 0x00, 0x2c, 0x12, 0x34, 0x00, 0x00,
        0x40, 0x06, 0x00, 0x00, 0xc0, 0xa8, 0x01, 0x0a,
        0xc0, 0xa8, 0x01, 0x14, 0x01, 0x02, 0x03, 0x04,
        0xc8, 0x22, 0x00, 0x16, 0x00, 0x00, 0x00, 0x01,
        0x00, 0x00, 0x00, 0x00, 0x50, 0x02, 0x20, 0x00,
        0x00, 0x00, 0x00, 0x00
    };
    PacketInfo info;

    assert(parse_packet(packet, sizeof(packet), sizeof(packet), &info));
    assert(info.has_ipv4);
    assert(info.ipv4_ihl == 24U);
    assert(info.has_tcp);
    assert(info.src_port == 51234U);
    assert(info.dst_port == 22U);
    assert((info.tcp_flags & TH_SYN) != 0U);
}

static void test_ipv4_fragment_without_l4(void)
{
    static const uint8_t packet[] = {
        0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff,
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55,
        0x08, 0x00,
        0x45, 0x00, 0x00, 0x1c, 0x12, 0x34, 0x00, 0x01,
        0x40, 0x06, 0x00, 0x00, 0xc0, 0xa8, 0x01, 0x0a,
        0xc0, 0xa8, 0x01, 0x14
    };
    PacketInfo info;

    assert(parse_packet(packet, sizeof(packet), sizeof(packet), &info));
    assert(info.has_ipv4);
    assert(info.ipv4_fragmented);
    assert(!info.ipv4_l4_header_available);
    assert(!info.has_tcp);
}

static void test_icmp_echo_request(void)
{
    static const uint8_t packet[] = {
        0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff,
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55,
        0x08, 0x00,
        0x45, 0x00, 0x00, 0x1c, 0x12, 0x34, 0x00, 0x00,
        0x40, 0x01, 0x00, 0x00, 0xc0, 0xa8, 0x01, 0x0a,
        0xc0, 0xa8, 0x01, 0x14,
        0x08, 0x00, 0x00, 0x00, 0x12, 0x34, 0x00, 0x01
    };
    PacketInfo info;

    assert(parse_packet(packet, sizeof(packet), sizeof(packet), &info));
    assert(info.has_icmp);
    assert(info.icmp_type == ICMP_ECHO);
}

int main(void)
{
    test_truncated_ethernet();
    test_arp_request();
    test_ipv4_tcp_with_options();
    test_ipv4_fragment_without_l4();
    test_icmp_echo_request();

    puts("parser_synthetic: all checks passed");
    return 0;
}
